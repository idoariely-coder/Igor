export const ALL_SUBTOPICS = UNITS.flatMap((u) => u.subtopics.map((s) => ({ ...s, unitId: u.id, unitTitle: u.title, color: u.color, emoji: u.emoji })));

export function findUnit(id) {
  return UNITS.find((u) => u.id === id) || null;
}

export function findSubtopic(id) {
  return ALL_SUBTOPICS.find((s) => s.id === id) || null;
}

// "topicId" באפליקציה = מזהה תת-נושא. מחזיר תיאור קריא לפרומפטים.
export function describeTopic(id) {
  const s = findSubtopic(id);
  if (!s) return '';
  return `${s.unitTitle} → ${s.title} (מיומנויות: ${s.skills.join(', ')})`;
}

